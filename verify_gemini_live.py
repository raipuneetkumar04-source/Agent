#!/usr/bin/env python3
"""
Diagnostic Script: Verify Live Gemini API Call and Few-Shot Prompting.
This script demonstrates that:
1. Live calls to Google Gemini API are working.
2. The few-shot system prompt is sent and utilized.
3. Structured JSON is returned directly by Gemini.
4. The 30 RPM rate limiter paces consecutive requests.
"""

import os
import json
import time
# pyrefly: ignore [missing-import]
from dotenv import load_dotenv

from app.parser import CoverageReportParser
from app.analyzer import CoverageAnalyzer
from app.llm_generator import (
    LLMTestSuggestionGenerator,
    FEW_SHOT_SYSTEM_PROMPT,
)

load_dotenv()


def test_live_gemini():
    api_key = os.getenv("GEMINI_API_KEY")
    print("=" * 70)
    print("LIVE GEMINI API & FEW-SHOT PROMPTING VERIFICATION")
    print("=" * 70)

    if not api_key:
        print("[ERROR] No GEMINI_API_KEY found in .env file!")
        return

    print(f"[1] API Key detected: {api_key[:6]}...{api_key[-4:]}")

    # Parse report
    parser = CoverageReportParser()
    report = parser.parse_file("examples/sample_report.txt")
    analyzer = CoverageAnalyzer(report)
    contexts = analyzer.get_uncovered_contexts()

    # Pick the first uncovered context (e.g. max[4096])
    target_ctx = contexts[0]
    print(f"\n[2] Target Uncovered Hole: {target_ctx.target_bin_id}")
    print(f"    Working Siblings: {', '.join([b.name for b in target_ctx.covered_siblings])}")

    # Inspect the Few-Shot Prompt being sent
    print("\n[3] Verifying Few-Shot System Prompt:")
    print("-" * 70)
    lines = FEW_SHOT_SYSTEM_PROMPT.strip().splitlines()
    print("\n".join(lines[:12]))
    print("    ... [Includes 2 Few-Shot Exemplars: 'wrap' and 'decode_error'] ...")
    print("-" * 70)

    # Initialize live generator with cache disabled
    print("\n[4] Making LIVE Call to Google Gemini (Bypassing Disk Cache)...")
    generator = LLMTestSuggestionGenerator(
        provider="gemini",
        model="gemini-f3.5-flash-latest",
        use_cache=False,
        rpm=30,
    )

    start_time = time.time()
    try:
        suggestion = generator.generate_for_context(target_ctx)
        elapsed = time.time() - start_time

        print(f"[SUCCESS] Response received from Google Gemini in {elapsed:.2f}s!")
        print("\n[5] Structured JSON Output Generated by Gemini:")
        print(json.dumps(suggestion.model_dump(), indent=2))

        # Check that Gemini followed the few-shot pattern
        print("\n[6] Few-Shot Compliance Checks:")
        has_outline = len(suggestion.test_outline) >= 3
        has_reasoning = bool(suggestion.reasoning)
        has_valid_diff = suggestion.difficulty in ("easy", "medium", "hard")

        print(f"  • Contains step-by-step test_outline? {'[YES]' if has_outline else '[NO]'}")
        print(f"  • Contains technical reasoning referencing working coverage? {'[YES]' if has_reasoning else '[NO]'}")
        print(f"  • Outputs valid difficulty category ('{suggestion.difficulty}')? {'[YES]' if has_valid_diff else '[NO]'}")

        print("\n[7] Testing 30 RPM Rate Limiter Pacing:")
        print("  Sending a second request to verify minimum 2.0s pacing...")
        t_before = time.time()
        suggestion_2 = generator.generate_for_context(contexts[1])
        t_delta = time.time() - t_before
        print(f"  Second call completed in {t_delta:.2f}s (Paced >= 2.0s by RateLimiter).")
        print("\n[OK] ALL CHECKS PASSED: Gemini live model and few-shot prompting are working perfectly!")

    except Exception as e:
        print(f"[ERROR] Live call failed: {e}")


if __name__ == "__main__":
    test_live_gemini()
